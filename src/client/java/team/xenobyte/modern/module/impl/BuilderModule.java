    public EditorPreview editorPreview(Minecraft client) {
        Block displayBlock = null;
        if (client != null && client.player != null) {
            displayBlock = selectedMaterial(client);
        }
        if (displayBlock == null) {
            displayBlock = draftBlock != null ? draftBlock : plannedBlock;
        }

        ItemStack stack = displayBlock == null ? ItemStack.EMPTY : new ItemStack(displayBlock);
        ResourceLocation id = displayBlock == null ? null : BuiltInRegistries.BLOCK.getKey(displayBlock);
        String materialId = id == null ? "hold a block" : id.toString();
        String selectedShape = shape.choiceValue();
        int actualX;
        int actualY;
        int actualZ;
        int zoneCount = 0;
        if (selectedShape.startsWith("Zone") && client != null && client.level != null) {
            List<SelectedZoneRegistry.Zone> zones = SelectedZoneRegistry.snapshot(client.level.dimension());
            zoneCount = zones.size();
            if (!zones.isEmpty()) {
                SelectedZoneRegistry.Zone zone = zones.get(0);
                actualX = zone.max().getX() - zone.min().getX() + 1;
                actualY = zone.max().getY() - zone.min().getY() + 1;
                actualZ = zone.max().getZ() - zone.min().getZ() + 1;
            } else {
                actualX = width.intValue();
                actualY = height.intValue();
                actualZ = length.intValue();
            }
        } else if ("Floor".equals(selectedShape)) {
            actualX = width.intValue();
            actualY = 1;
            actualZ = length.intValue();
        } else if ("HollowBox".equals(selectedShape)) {
            actualX = width.intValue();
            actualY = height.intValue();
            actualZ = length.intValue();
        } else if ("Disc".equals(selectedShape) || "Ring".equals(selectedShape)) {
            actualX = radius.intValue() * 2 + 1;
            actualY = 1;
            actualZ = actualX;
        } else {
            actualX = radius.intValue() * 2 + 1;
            actualY = "Arena".equals(selectedShape) ? height.intValue() : actualX;
            actualZ = actualX;
        }

        List<PreviewVoxel> voxels = createPreviewVoxels(selectedShape, actualX, actualY, actualZ);
        String dimensions = actualX + " x " + actualY + " x " + actualZ;
        if (selectedShape.startsWith("Zone")) {
            dimensions += " / " + zoneCount + " zone" + (zoneCount == 1 ? "" : "s");
        }
        return new EditorPreview(stack, materialId, dimensions, voxels);
    }

    private List<PreviewVoxel> createPreviewVoxels(String selectedShape, int actualX, int actualY, int actualZ) {
        int maxActual = Math.max(1, Math.max(actualX, Math.max(actualY, actualZ)));
        double scale = Math.min(1.0D, 6.0D / maxActual);
        int sizeX = Math.max(1, (int)Math.round(actualX * scale));
        int sizeY = Math.max(1, (int)Math.round(actualY * scale));
        int sizeZ = Math.max(1, (int)Math.round(actualZ * scale));
        int shell = Math.max(1, (int)Math.ceil(thickness.intValue() * scale));
        LinkedHashSet<PreviewVoxel> output = new LinkedHashSet<>();

        if ("Disc".equals(selectedShape) || "Ring".equals(selectedShape)) {
            double centerX = (sizeX - 1) * 0.5D;
            double centerZ = (sizeZ - 1) * 0.5D;
            double radiusX = Math.max(0.5D, sizeX * 0.5D);
            double radiusZ = Math.max(0.5D, sizeZ * 0.5D);
            double inner = Math.max(0.0D, 1.0D - thickness.intValue() / (double)Math.max(1, radius.intValue()));
            for (int x = 0; x < sizeX; x++) {
                for (int z = 0; z < sizeZ; z++) {
                    double dx = (x - centerX) / radiusX;
                    double dz = (z - centerZ) / radiusZ;
                    double distance = dx * dx + dz * dz;
                    if (distance <= 1.0D && (!"Ring".equals(selectedShape) || distance >= inner * inner)) {
                        output.add(new PreviewVoxel(x, 0, z));
                    }
                }
            }
        } else if ("Sphere".equals(selectedShape) || "HollowSphere".equals(selectedShape)) {
            double centerX = (sizeX - 1) * 0.5D;
            double centerY = (sizeY - 1) * 0.5D;
            double centerZ = (sizeZ - 1) * 0.5D;
            double radiusX = Math.max(0.5D, sizeX * 0.5D);
            double radiusY = Math.max(0.5D, sizeY * 0.5D);
            double radiusZ = Math.max(0.5D, sizeZ * 0.5D);
            double inner = Math.max(0.0D, 1.0D - Math.max(1, shell) / (double)Math.max(1, Math.max(sizeX, sizeY)));
            for (int x = 0; x < sizeX; x++) {
                for (int y = 0; y < sizeY; y++) {
                    for (int z = 0; z < sizeZ; z++) {
                        double dx = (x - centerX) / radiusX;
                        double dy = (y - centerY) / radiusY;
                        double dz = (z - centerZ) / radiusZ;
                        double distance = dx * dx + dy * dy + dz * dz;
                        if (distance <= 1.0D && distance >= inner * inner) {
                            output.add(new PreviewVoxel(x, y, z));
                        }
                    }
                }
            }
        } else if ("Arena".equals(selectedShape)) {
            double centerX = (sizeX - 1) * 0.5D;
            double centerZ = (sizeZ - 1) * 0.5D;
            double radiusX = Math.max(0.5D, sizeX * 0.5D);
            double radiusZ = Math.max(0.5D, sizeZ * 0.5D);
            double inner = Math.max(0.0D, 1.0D - shell / (double)Math.max(1, Math.max(sizeX, sizeZ)));
            for (int x = 0; x < sizeX; x++) {
                for (int z = 0; z < sizeZ; z++) {
                    double dx = (x - centerX) / radiusX;
                    double dz = (z - centerZ) / radiusZ;
                    double distance = dx * dx + dz * dz;
                    if (distance <= 1.0D) {
                        output.add(new PreviewVoxel(x, 0, z));
                    }
                    if (distance <= 1.0D && distance >= inner * inner) {
                        for (int y = 1; y < sizeY; y++) {
                            output.add(new PreviewVoxel(x, y, z));
                        }
                    }
                }
            }
        } else {
            boolean floor = "Floor".equals(selectedShape);
            boolean wallsOnly = "ZoneWalls".equals(selectedShape);
            for (int x = 0; x < sizeX; x++) {
                for (int y = 0; y < sizeY; y++) {
                    for (int z = 0; z < sizeZ; z++) {
                        boolean xEdge = x < shell || sizeX - 1 - x < shell;
                        boolean yEdge = y < shell || sizeY - 1 - y < shell;
                        boolean zEdge = z < shell || sizeZ - 1 - z < shell;
                        boolean visibleSurface = xEdge || yEdge || zEdge;
                        if (floor ? y == 0 : wallsOnly ? xEdge || zEdge : visibleSurface) {
                            output.add(new PreviewVoxel(x, y, z));
                        }
                    }
                }
            }
        }
        return List.copyOf(output);
    }

