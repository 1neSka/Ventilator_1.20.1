    @Override
    public void onWorldRender(WorldRenderContext context) {
        if (!preview.boolValue()) {
            return;
        }
        if (!draftPositions.isEmpty()) {
            List<AABB> boxes = draftPositions.stream().limit(PREVIEW_LIMIT).map(AABB::new).toList();
            int fillColor = draftState == DraftState.LOCKED ? 0x20ffd65a : 0x1855d6ff;
            int outlineColor = draftState == DraftState.LOCKED ? 0xccffd65a : 0xaa55d6ff;
            RenderUtil.drawFilledBoxesImmediate(context, boxes, fillColor);
            RenderUtil.drawBoxesImmediate(context, boxes, outlineColor);
            return;
        }
        if (!pending.isEmpty()) {
            List<AABB> boxes = pending.stream().limit(PREVIEW_LIMIT).map(AABB::new).toList();
            RenderUtil.drawFilledBoxesImmediate(context, boxes, 0x1855d6ff);
            RenderUtil.drawBoxesImmediate(context, boxes, 0xaa55d6ff);
        }
    }

